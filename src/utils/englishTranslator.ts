export function translateTurkishToEnglish(raw: string, mode: TranslationMode = 'full'): string {
  if (!raw) return raw;
  const leading = raw.match(/^\s*/)?.[0] || '';
  const trailing = raw.match(/\s*$/)?.[0] || '';
  const core = raw.trim();
  if (!core) return raw;

  // 1. Exact title match (active in both 'titles' and 'full')
  if (TITLE_PHRASES[core]) {
    return `${leading}${TITLE_PHRASES[core]}${trailing}`;
  }

  // 2. Exact full-mode match (active ONLY in 'full')
  if (mode === 'full' && FULL_MODE_PHRASES[core]) {
    return `${leading}${FULL_MODE_PHRASES[core]}${trailing}`;
  }

  // 3. Numbered or emoji prefix match (e.g. "1. Noktalama İşaretleri", "🎯 Geometri Tahtası")
  const prefixMatch = core.match(/^((?:\d+\.\s*)|(?:[^\w\sçğıöşüÇĞİÖŞÜ]+\s+))(.*)$/);
  if (prefixMatch) {
    const [, prefix, rest] = prefixMatch;
    if (TITLE_PHRASES[rest]) {
      return `${leading}${prefix}${TITLE_PHRASES[rest]}${trailing}`;
    }
    if (mode === 'full' && FULL_MODE_PHRASES[rest]) {
      return `${leading}${prefix}${FULL_MODE_PHRASES[rest]}${trailing}`;
    }
  }

  // 4. Safe title regexes (active in both 'titles' and 'full')
  for (const [regex, replacement] of TITLE_REGEX_PATTERNS) {
    if (regex.test(core)) {
      const out = core.replace(regex, replacement as any);
      if (out !== core) return `${leading}${out}${trailing}`;
    }
  }

  // 5. Full-sentence regexes (active ONLY in 'full')
  if (mode === 'full') {
    for (const [regex, replacement] of FULL_REGEX_PATTERNS) {
      if (regex.test(core)) {
        const out = core.replace(regex, replacement as any);
        if (out !== core) return `${leading}${out}${trailing}`;
      }
    }
  }

  return raw;
}
